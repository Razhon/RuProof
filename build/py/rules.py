def kak_compare(comma):
    """Антипаттерны KAK_PRAVILO: «как обычно/всегда…» после слова сравнения (такой, столь, более, так же) — не вводное.
    Только обычно/всегда/сейчас: «такие люди, как правило,» — вводное. Между ними одно слово, но не знак и не оборот
    (таким образом, в таком случае, более того), иначе глушатся настоящие пропуски; «тем более» — не сравнение.
    shortcut: одно слово между; «менее» и голое «так» не берём (менее часа, так устал)."""
    sep = "<token>,</token>" if comma else ""
    tail = f'{sep}<token>как</token><token regexp="yes">обычно|всегда|сейчас</token></antipattern>'
    return (
        '<antipattern><token inflected="yes" regexp="yes">такой|столь|настолько|более'
        '<exception scope="previous">тем</exception></token>'
        f'<token min="0" negate="yes" regexp="yes">&pnct;|образом|случае|того</token>{tail}\n                '
        f"<antipattern><token>так</token><token>же</token>{tail}"
    )


