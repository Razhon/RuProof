def notice(x, text):
    """Вставить пометку об изменении (LGPL 2.1, раздел 2b) сразу после XML-декларации."""
    i = x.index("?>") + 2
    return x[:i] + "\n" + text + x[i:]


def span(x, rid):
    m = re.search(rf'<(rulegroup|rule)\b[^>]*\bid="{re.escape(rid)}"', x)
    if not m:  # не assert: apply и diff ловят это как штатную ветку, а python -O выкинул бы проверку
        raise LookupError(f"правило {rid} не найдено")
    end = x.index(f"</{m.group(1)}>", m.end()) + len(m.group(1)) + 3
    return m.start(), end


def add_id(xml):
    m = re.search(r'id="([^"]+)"', xml)
    if not m:
        sys.exit(f"ADD: у правила нет id: {' '.join(xml.split())[:80]}")
    return m.group(1)


def known(ids):
    """id из PATCHES/ADD; опечатка — выход с похожими, а не молча пустая проверка."""
    have = {p.rid for p in PATCHES} | {a.rid for a in ADD}
    for i in ids:
        if i not in have:
            sys.exit(f"{i}: нет в PATCHES/ADD; похожие: {', '.join(difflib.get_close_matches(i, have)) or '—'}")
    return set(ids)


def patch_one(x, p):
    """Одна правка PATCHES внутри своего правила -> (новый текст, число совпадений, совпавшие фрагменты)."""
    a, b = span(x, p.rid)
    found = [m.group(0) for m in re.finditer(p.rx, x[a:b])]
    return x[:a] + re.sub(p.rx, p.new, x[a:b]) + x[b:], len(found), found


def parsed(x, name):
    """Сломанный XML (незакрытый тег в ADD) — ошибка сборки здесь, а не невнятный отказ LT при старте."""
    try:
        ET.fromstring(x)
    except ET.ParseError as e:
        n = e.position[0]
        sys.exit(f"FAIL {name} не разбирается: {e}\n  строка {n}: {x.splitlines()[n - 1].strip()[:200]}")
    return x


def apply(x):
    x0, bad = x, []  # все несовпадения сразу: после обновления образа ломается обычно несколько правок
    for p in PATCHES:
        rid, count = p.rid, p.count
        try:
            x, n, found = patch_one(x, p)
        except LookupError as e:
            bad.append(f"FAIL {e} (правило в образе изменилось?)")
            continue
        if n != count:
            where = x0.count("\n", 0, span(x0, rid)[0]) + 1
            bad.append(f"FAIL {rid}: совпадений {n}, ожидалось {count}; правило: build/.work/grammar.orig.xml:{where}")
            bad += [f"  {' '.join(f.split())[:100]}" for f in found[:3]]
    for after, xml, _, _ in ADD:
        rid = add_id(xml)
        if f'id="{rid}"' in x:
            bad.append(f"FAIL {rid} уже есть в образе")
            continue
        try:
            _, b = span(x, after)
            x = x[:b] + xml + x[b:]
        except LookupError as e:
            bad.append(f"FAIL {rid}: {e}, после него вставлять")
    if bad:
        sys.exit("\n".join(bad))
    return parsed(notice(x, GRAMMAR_NOTICE), "grammar.xml")


def wait(url):
    for _ in range(60):  # сервер только что (пере)запущен: с ngrams ~30 с; не дольше ~4 мин, а не ждать вечно
        try:
            urllib.request.urlopen(url + "/v2/languages", timeout=2)
            return
        except OSError:
            time.sleep(2)
    sys.exit(f"FAIL LanguageTool не отвечает на {url}: podman compose logs languagetool")


def lt(url, texts, rules=(), only=False):
    """Один запрос на все тексты (их разделяют пустые строки) -> замечания по каждому тексту, смещения от его начала.
    rules: включить эти правила (и выключенные); only: только их."""
    q = {"text": "\n\n".join(texts), "language": "ru-RU", "level": "picky"}
    if rules:
        q["enabledRules"] = ",".join(rules)
        if only:
            q["enabledOnly"] = "true"
    ms = json.load(urllib.request.urlopen(url + "/v2/check", urllib.parse.urlencode(q).encode()))["matches"]
    out, pos = [], 0
    for t in texts:
        # смещения UTF-16 совпадают: символов вне BMP нет
        out.append([dict(m, offset=m["offset"] - pos) for m in ms if pos <= m["offset"] < pos + len(t)])
        pos += len(t) + 2
    return out


def show(m, t):
    """Замечание одной строкой: «фрагмент» → варианты: сообщение."""
    frag = t[m["offset"] : m["offset"] + m["length"]]
    sugs = "|".join(r["value"] for r in m["replacements"][:3])
    msg = re.sub(r"<[^>]+>", "", m["message"])
    return f"«{frag}»" + (f" → {sugs}" if sugs else "") + f": {msg[:80]}"


def check(url, ids=()):
    wait(url)
    root = ET.parse(OUT).getroot()
    bad = 0

    def run(rid, cases, only, kind=None):
        """Случай — (want, текст) или, для обязательного, (True, (текст, первый вариант каждого замечания, …)): тогда замечаний
        правила ровно столько, с этими вариантами по порядку. only: только это правило, даже выключенное.
        kind: issueType, который должен быть у каждого замечания."""
        nonlocal bad
        texts = [t if isinstance(t, str) else t[0] for _, t in cases]
        for (want, t), found in zip(cases, lt(url, texts, [rid] if only else (), only)):
            t, sugs = (t, None) if isinstance(t, str) else (t[0], list(t[1:]))
            mine = [m for m in found if m["rule"]["id"] == rid]
            got = [(m["replacements"] or [{"value": None}])[0]["value"] for m in mine]
            if bool(mine) != want:
                fail = "не поймано" if want else f"ложное срабатывание {show(mine[0], t)}"
            elif sugs is not None and got != sugs:
                fail = f"варианты {got}, ожидались {sugs} ({'; '.join(show(m, t) for m in mine)})"
            else:
                types = [m["rule"]["issueType"] for m in mine]
                fail = next((f"issueType {t}, ожидался {kind}" for t in types if kind and t != kind), None)
            if fail and t not in KNOWN_FAIL:
                bad += 1
                print(f"FAIL {rid}: {fail}: {t}")

    patches = [p for p in PATCHES if not ids or p.rid in ids]
    added = [a for a in ADD if not ids or a.rid in ids]
    # покрытие: у каждого изменённого правила есть случаи
    for rid in {p.rid for p in patches} - {p.rid for p in patches if p.ok or p.must}:
        bad += 1
        print(f"FAIL {rid}: рядом с правками нет случаев")
    # покрытие: каждое новое правило закрепляет хотя бы один вариант
    for a in added:
        if not any(isinstance(t, tuple) for t in a.must):
            bad += 1
            print(f"FAIL {a.rid}: нет обязательного случая с вариантом исправления")
    for rid, ok, must in [(r.rid, r.ok, r.must) for r in patches + added]:
        el = next(e for e in root.iter() if e.tag in ("rule", "rulegroup") and e.get("id") == rid)
        ex = [
            (
                "correction" in e.attrib or e.get("type") == "incorrect",
                "".join(e.itertext()),
            )
            for e in el.iter("example")
        ]
        run(rid, ex, True)  # собственные примеры правила: шаблон всё ещё работает
        # случаи, с настройками сервера
        run(
            rid,
            [(False, t) for t in ok] + [(True, t) for t in must],
            False,
            el.get("type"),
        )
        print(f"{rid}: примеров {len(ex)}, случаев {len(ok) + len(must)}")
    if not ids:
        run(
            "SENTENCE_WHITESPACE",
            [(False, t) for t in SRX_OK] + [(True, t) for t in SRX_MUST],
            False,
        )
        print(f"segment.srx: случаев {len(SRX_OK) + len(SRX_MUST)}")
        run("PREP_K_and_Noun", [(True, t) for t in SYNTH_MUST], False)
        print(f"added.txt: случаев {len(SYNTH_MUST)}")
        for rid, case in REPLACE_CASES:
            run(rid, [case], False)
        print(f"replace.txt: случаев {len(REPLACE_CASES)}")
    sys.exit(1 if bad else 0)


def diff(ids):
    """Правила образа до и после правок; все правки применяются по порядку, печатаются выбранные."""
    if not SRC.exists():
        sys.exit(f"нет {SRC}: сначала rpdict")
    x = SRC.read_text(encoding="utf-8")
    for p in PATCHES:
        rid = p.rid
        try:
            a, b = span(x, rid)
        except LookupError as e:  # правило убрали из образа: остальные правки всё равно показать
            print(f"== {rid}: {e}")
            continue
        before = x[a:b]
        x, n, _ = patch_one(x, p)
        if ids and rid not in ids:
            continue
        a, b = span(x, rid)
        print(f"== {rid}: совпадений {n}, ожидалось {p.count}")
        print("\n".join(list(difflib.unified_diff(before.splitlines(), x[a:b].splitlines(), n=1, lineterm=""))[2:]))
    for after, xml, _, _ in ADD:
        if not ids or add_id(xml) in ids:
            print(f"== {add_id(xml)}: новое, после {after}{xml}")


def phrases(s):
    """Фразы файла для try: разделитель — пустая строка, перенос внутри фразы — пробел."""
    return [p.strip().replace("\n", " ") for p in re.split(r"\n\s*\n", s.replace("\r", "")) if p.strip()]


def unknown(ids, x):
    """Предупреждения о id, которых нет в grammar.xml x: Java-правило (SENTENCE_WHITESPACE) или опечатка."""
    have = set(re.findall(r'<(?:rule|rulegroup)\b[^>]*\bid="([^"]+)"', x))
    return [
        f"! {i}: нет в grammar.xml (Java-правило или опечатка); похожие: "
        + (", ".join(difflib.get_close_matches(i, have)) or "—")
        for i in sorted(ids - have)
    ]


def probe(url, path, ids):
    """Текст только из файла: кириллица в аргументах Git Bash и PowerShell портится."""
    ts = phrases(Path(path).read_text(encoding="utf-8-sig"))
    if not ts:
        sys.exit(f"{path}: нет фраз")
    # смещения LT в UTF-16, у lt() — в символах: вне BMP (эмодзи) замечания разъедутся по фразам
    if any(ord(c) > 0xFFFF for t in ts for c in t):
        sys.exit(f"{path}: символы вне BMP (эмодзи) не поддерживаются, уберите их")
    # LT молча игнорирует неизвестный id: без предупреждения опечатка выглядит как «правило не срабатывает»
    if ids and OUT.exists():
        print(*unknown(ids, OUT.read_text(encoding="utf-8")), sep="\n")
    wait(url)
    for t, ms in zip(ts, lt(url, ts, sorted(ids))):
        print(t)
        ms = [m for m in ms if not ids or m["rule"]["id"] in ids]
        for m in ms:
            print(f"  {m['rule']['id']} [{m['rule']['issueType']}] {show(m, t)}")
        if not ms:
            print("  —")


def apply_srx(x):
    assert x.count(SRX_RU) == 1, "в segment.srx нет русских правил (образ изменился?)"
    # первым: срабатывает первое подходящее правило SRX
    return parsed(notice(x.replace(SRX_RU, SRX_RU + SRX_RULE), SRX_NOTICE), "segment.srx")


def apply_replace(x):
    """replace.txt без записей REPLACE_DROP; каждая должна быть в образе ровно раз, иначе — все несовпадения сразу."""
    lines = x.split("\n")
    keys = [ln.split("=")[0].strip() if "=" in ln and not ln.startswith("#") else None for ln in lines]
    bad = [
        f"FAIL replace.txt: записей «{k}» {keys.count(k)}, ожидалась 1"
        for k in sorted(REPLACE_DROP)
        if keys.count(k) != 1
    ]
    if bad:
        sys.exit("\n".join(bad) + "\n  (список в образе изменился? build/.work/replace.orig.txt)")
    return REPLACE_NOTICE + "\n".join(ln for ln, k in zip(lines, keys) if k not in REPLACE_DROP)


