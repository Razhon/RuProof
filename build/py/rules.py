def neut_rule(noun, homograph, first, second, example):
    """Одно правило группы SoglasovanieNN_Verb_Neut: noun — postag-условие существительного, first/second — род вариантов."""
    verb = 'postag="VB:Past:.*:Neut" postag_regexp="yes" skip="-1"'
    if homograph:
        verb += f' regexp="yes">.*сь|{NEUT_SAY}<exception negate_pos="yes" postag="VB:Past:.*" postag_regexp="yes"/>'
        verb += f'<exception inflected="yes" regexp="yes">{NEUT_SKIP}|{NEUT_COUNT}</exception>'
        neg, no = "", 3
    else:
        # пришло: есть и чтение «пришлый» (ADJ:Short)
        verb += '><exception negate_pos="yes" postag="VB:Past:.*|ADJ:Short:.*" postag_regexp="yes"/>'
        verb += '<exception postag="VB:Past:bezl.*" postag_regexp="yes"/>'
        verb += f'<exception inflected="yes" regexp="yes">{NEUT_SKIP}</exception>'
        neg, no = '<token min="0">не</token>', 4
    sug = (
        f'<suggestion><match no="{no}" postag="VB:Past:.*" postag_regexp="yes" postag_replace="VB:Past:.*:.*:{g}"/></suggestion>'
        for g in (first, second)
    )
    return f"""
            <rule>
                <pattern>
                    <token postag="SENT_START" skip="-1"><exception scope="next" postag="NN:.*:Neut:Sin:Nom" postag_regexp="yes"/><exception scope="next" postag="PNN:.*" postag_regexp="yes"/><exception scope="next" regexp="yes">{NEUT_Q}</exception></token>
                    <token {noun}</token>
                    {neg}
                    <marker>
                        <token {verb}<exception scope="next" postag="(P?NN|ADJ:MPR):.*Nom.*" postag_regexp="yes"/></token>
                    </marker>
                    <token regexp="yes">[.;:,!?…—–]</token>
                </pattern>
                <message suppress_misspelled="yes">Существительное не согласуется с глаголом по роду: {" или ".join(sug)}.</message>
                <short>Ошибка в согласовании по роду</short>
                {example}
            </rule>"""


