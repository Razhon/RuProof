# слова вне нормы (rpdict -u, store.NONSTD): замечание стиля, в prose его снимает прокси (ключ nonstandard).
# Почему не тег :Talk, как у правила talk из образа: шаблон postag сравнивается с тегом целиком, и NN:.*:.*:Nom уже не
# видит …:Nom:Talk. Прогон 1644 шаблонов grammar.xml по 644 тегам tagged.txt: −9 % совпадений (:Talk в конце), −5 %
# (после части речи), в том числе в согласовании, а у междометия — 4 исключения Verb_comma_Verb. Поэтому теги слова не
# трогаются, а отмечает его отдельное правило: оно только читает текст и другим правилам ничего не меняет
NONSTD_MSG = (
    "Слово вне литературной нормы (разговорное, просторечное, новое или жаргонное): уместно в художественном тексте "
    "и переписке; в официальном или нейтральном тексте его лучше {}"
)


def nonstandard(words):
    """Группа RU_NONSTANDARD по {слово: замена}: сначала по правилу на слово с заменой, последним — общее на все слова
    (первое подходящее правило группы гасит остальные на том же месте). Правило с заменой ловит только точную форму:
    замена не склоняется (чуваков -> «парень» неверно). Общее ловит и лемму (inflected: чувак ловит чуваков), и точную
    форму: у слова только из spelling/ignore нет разбора, inflected его не видит."""

    def token(ws, inflected):
        rx = escape("|".join(re.escape(w) for w in sorted(ws)))
        exact = f'<token regexp="yes">{rx}</token>'
        return f'<or><token inflected="yes" regexp="yes">{rx}</token>{exact}</or>' if inflected else exact

    def rule(ws, val):
        rep, url = split_url(val)
        tail = f"заменить: <suggestion>{escape(rep)}</suggestion>." if rep else "заменить или убрать."
        w = escape(min(ws))
        return f"""
            <rule>
                <pattern>{token(ws, not rep)}</pattern>
                <message>{NONSTD_MSG.format(tail)}</message>{url_tag(url)}
                <short>Слово вне нормы</short>
                <example correction="{escape(rep, {'"': "&quot;"})}"><marker>{w}</marker>.</example>
            </rule>"""

    if not words:
        return ""
    rules = "".join(rule([w], r) for w, r in sorted(words.items()) if r) + rule(list(words), "")
    return f'\n        <rulegroup id="RU_NONSTANDARD" type="style" name="Слова вне нормы">{rules}\n        </rulegroup>'


def url_tag(url):
    """Ссылка-подтверждение из строки списка: кнопка «Подробнее» у замечания."""
    return f"\n                <url>{escape(url)}</url>" if url else ""


# prohibited.txt (rpdict -p) со строкой «слово = замена»: слово вычтено из словаря, но speller ищет замену по одной
# правке среди однословных форм и не находит дефисную или раздельную (мда -> «м-да», нахер -> «на хер», распросы ->
# «Распр осы»). Правило на слово даёт подсказку из файла; слово без замены отмечает speller. Фразу (во внутрь)
# speller не видит: её слова верны по отдельности, поэтому ловит только правило, и замена у фразы обязательна (rpdict -p)
# Слово с заглавной (Лавкрафтовский) speller принимает везде, раз знает строчное: правило отмечает его в середине
# предложения, кроме места после открывающей кавычки, скобки, тире, двоеточия (там заглавная бывает верна: прямая
# речь, цитата). С меткой * (Лавкрафтовский*) — все формы слова, подсказка — найденная форма строчными
CAP_BEFORE = '<token postag="SENT_START" negate_pos="yes"><exception regexp="yes">[«"„“(\\[—–:…-]</exception></token>'


def prohibited(pairs):
    def rule(k, val):
        rep, url = split_url(val)
        w = k.rstrip("*")
        if w == w.lower() or " " in w:  # фраза (во внутрь): токен на слово, без учёта регистра, как строчное слово
            tok = "".join(f'<token regexp="yes">{escape(re.escape(p))}</token>' for p in w.lower().split())
            sug, msg, before = escape(rep), "", ""
        elif k.endswith("*"):
            low = escape(w.lower())
            tok = (
                f'<or><token inflected="yes">{low}<exception case_sensitive="yes" regexp="yes">\\p{{Ll}}.*'
                f'</exception></token><token case_sensitive="yes">{escape(w)}</token></or>'
            )
            rep, sug, msg, before = w.lower(), '<match no="2" case_conversion="alllower"/>', "Со строчной: ", CAP_BEFORE
        else:
            rep = rep or w.lower()
            tok, sug, msg = f'<token case_sensitive="yes">{escape(w)}</token>', escape(rep), "Со строчной: "
            before = CAP_BEFORE
        pattern = f"{before}<marker>{tok}</marker>" if before else tok
        ex = f"Это <marker>{escape(w)}</marker> ужас." if before else f"<marker>{escape(w)}</marker>."
        return f"""
            <rule>
                <pattern>{pattern}</pattern>
                <message>{msg or "Неверное написание: "}<suggestion>{sug}</suggestion>.</message>{url_tag(url)}
                <short>Неверное написание</short>
                <example correction="{escape(rep, {'"': "&quot;"})}">{ex}</example>
            </rule>"""

    # фраза без замены (вписана руками) правила не получает: пустая подсказка хуже, чем ничего
    rules = "".join(
        rule(k, v) for k, v in sorted(pairs.items()) if split_url(v)[0] or (k != k.lower() and " " not in k)
    )
    return (
        f'\n        <rulegroup id="RU_PROHIBITED" name="Неверное написание">{rules}\n        </rulegroup>'
        if rules
        else ""
    )


