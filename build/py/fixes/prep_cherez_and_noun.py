#!/usr/bin/env python3
"""док-код: docs/rules/PREP_cherez_and_Noun.md

Правки правила PREP_cherez_and_Noun («через», «сквозь» + не вин. п.): кортежи PATCHES в формате Patch из rules.py,
их же загружает load_fixes. Норма, причины и отклонённые варианты — в документе.
"""

# вторая часть диапазона через дефис: «десять-пятнадцать», «пятьсот-шестьсот», «10-15» — один токен без тега
RANGE = (
    r"[а-яё]+-(два|две|три|четыре|пять|шесть|семь|восемь|девять|десять|[а-яё]+надцать|двадцать|тридцать|сорок"
    r"|[а-яё]+десят|девяносто|сто|двести|триста|четыреста|[а-яё]+сот|полтора|полторы)|[0-9]+[-–][0-9]+"
)
HEAD = r'<antipattern><token regexp="yes">сквозь|через</token><token postag="NN:.*:R" postag_regexp="yes"/>'

PATCHES = [
    # приблизительность инверсией: род. п. существительного требует числительное, а не предлог, само числительное
    # в вин. п. (Через секунд десять Брумзик вышел.); то же с «этак», «с» перед числительным и с диапазоном через дефис
    (
        "PREP_cherez_and_Noun",
        r'(<rule default="on" id="PREP_cherez_and_Noun"[^>]*>\s*)(<pattern)',
        (
            rf'\1{HEAD}<token min="0" regexp="yes">этак|эдак|так|с</token>'
            r'<token postag="Num.*:(Nom|V)|NumD.*" postag_regexp="yes"/></antipattern>\n            '
            rf'{HEAD}<token regexp="yes">{RANGE}</token></antipattern>\n            \2'
        ),
        1,
        [
            "Через секунд десять Брумзик уже вышел.",
            "Через часов пять он проснулся.",
            "Через шагов двадцать он остановился.",
            "Через секунд двадцать пять всё стихло.",
            "Через часа два он вернулся.",
            "Через дня четыре пришло письмо.",
            "Через секунд 10 он вышел.",
            "«Через секунд десять», — сказал Брумзик.",
            "Он вышел через секунд десять.",
            "Через секунд этак десять он вышел.",
            "Через секунд десять-пятнадцать он вышел.",
            "Через рублей пятьсот-шестьсот он купил дом.",
            "Через секунд 10-15 он вышел.",
            "Через минут пять Брумзик вернулся.",
            "Через метров сто будет поворот.",
            "Через лет двадцать город изменится.",
        ],
        [
            ("Через секунд Брумзик вышел.", "Через секунды"),
            ("Через часов мы вернулись.", "Через часы"),
            ("Луч света попал сквозь окном в комнату.", "сквозь окно"),
            ("Брумзик перелез через стеной.", "через стену"),
            ("Через дней двум он вернулся.", "Через дни"),
        ],
    ),
    # омоним-наречие, глагол или краткое прилагательное не снимает существительное: после предлога это не может
    # быть ничем, кроме существительного (Мы шли через лесом. Через минут он вышел.)
    (
        "PREP_cherez_and_Noun",
        r'(<exception postag="NN:\.\*:\.\*:\.\*\|)(SENT_END\|PARA_END" negate_pos="yes")',
        r"\1ADV|VB.*|ADJ:Short.*|\2",
        1,
        [
            "Он прошёл через лес.",
            "Через минуту он вышел.",
            "Через силу он улыбнулся.",
            "Через край перелилась вода.",
            "Через минут десять-пятнадцать он вышел.",
        ],
        [
            ("Мы шли через лесом.", "через лес"),
            ("Сквозь лесом пробивался свет.", "Сквозь лес"),
            ("Через минут он вышел.", "Через минуты"),
            ("Через полем шла дорога.", "Через поле"),
        ],
    ),
    # «лет» (лёт:V): чтение вин. п. из словаря, в тексте это род. п. от «год» (Через лет он вернулся.); «метров»
    # (метр:Anim:V) не берём: синтез из того же чтения даёт первой заменой «Через метров», то есть сам текст
    (
        "PREP_cherez_and_Noun",
        r'<exception postag="NN:\.\*:\.\*:V" postag_regexp="yes">',
        r'<exception postag="NN:.*:.*:V" postag_regexp="yes" regexp="yes">(?iu)(?!лет$).*',
        1,
        ["Через лет десять он вернулся.", "Через лет пятьдесят никто не вспомнит.", "Через метров он свернул."],
        [("Через лет он вернулся.", "Через год"), ("Через лет десяти он вернулся.", "Через год")],
    ),
]
