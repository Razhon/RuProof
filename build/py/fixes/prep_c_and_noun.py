#!/usr/bin/env python3
"""док-код: docs/rules/PREP_C_and_Noun.md

Правки правила PREP_C_and_Noun (предлог «с» и падеж существительного): кортежи PATCHES и ADD в формате Patch и Add
из rules.py, их же загружает load_fixes. Норма, причины и отклонённые варианты — в документе.
"""

# слова размера в тв. п., при которых «с» + вин. п. — сравнение по величине («ростом с сестру», «с сестру ростом»)
SIZE = (
    "величиной|величиною|размером|объёмом|объемом|длиной|длиною|высотой|высотою|вышиной|вышиною|шириной|шириною"
    "|ростом|весом|толщиной|толщиною|глубиной|глубиною"
)
# слова меры в вин. п.: «с» в значении «около» («с полчаса», «с неделю», «с километр»)
MEASURE = (
    '<exception inflected="yes" regexp="yes" postag="NN:.*:V" postag_regexp="yes">'
    "секунда|минута|минутка|час|часок|день|денёк|сутки|неделя|месяц|год|годик|век"
    "|километр|метр|сантиметр|миллиметр|верста|шаг|миля|литр|килограмм|кило|грамм|тонна"
    "|ведро|стакан|ложка|сотня|тысяча|десяток|дюжина|пуд|фунт"
    "|пол-?(секунды|минуты|часа|дня|суток|недели|месяца|года|века|километра|метра|версты|литра|ведра|стакана"
    "|сотни|тысячи|дюжины)</exception>"
)
# второй родительный на «-у/-ю» бывает только у неодушевлённых мужского рода («с испугу», «с краю»)
GEN2 = '<exception regexp="yes" postag="NN:Inanim:Masc:.*" postag_regexp="yes">[а-яё]*[ую]</exception>'

PATCHES = [
    # «с» с винительным в значении «около» — норма (Брумзик ждал с полчаса, с неделю, прошёл с километр): слова меры
    # времени, расстояния и количества в вин. п. не отмечаем
    (
        "PREP_C_and_Noun",
        r"(<exception regexp=\"yes\">\[а-я\]\*у\|\[!\.\?\]</exception>)",
        r"\1" + MEASURE,
        1,
        [
            "Брумзик ждал с полчаса.",
            "Где-то с полминуты Брумзик простоял у окна.",
            "Брумзик ждал с неделю.",
            "Брумзик прошёл с километр.",
        ],
        [("Брумзик гулял с собака.", None)],
    ),
    # окончание «-у/-ю» после «с» верно только у второго родительного неодушевлённых мужского рода (с испугу, с краю);
    # вин. п. женского рода и дат. п. на «-у» — ошибка (Брумзик говорил с сестру, пришёл с брату)
    (
        "PREP_C_and_Noun",
        r"<exception regexp=\"yes\">\[а-я\]\*у\|\[!\.\?\]</exception>",
        r'<exception regexp="yes">[!.?]</exception>' + GEN2,
        1,
        [
            "С испугу Брумзик выронил чашку.",
            "Брумзик сидел с краю.",
            "Они встретились с глазу на глаз.",
            "Брумзик ждал с минуту.",
        ],
        [("Брумзик говорил с сестру.", None), ("Брумзик гулял с собаку.", None), ("Брумзик пришёл с брату.", None)],
    ),
    # «с» + вин. п. рядом со словом размера — сравнение по величине (Брумзик ростом с сестру): в образе список неполон
    (
        "PREP_C_and_Noun",
        r'scope="previous">величиной\|размером\|объёмом\|объемом\|длиной\|высотой\|шириной<',
        rf'scope="previous">{SIZE}<',
        1,
        ["Брумзик ростом с сестру.", "Брумзик был ростом с маму.", "Мешок весом с собаку.", "Доска толщиной с ладонь."],
        [("Брумзик говорил с сестру.", None)],
    ),
    # то же при обратном порядке: слово размера после существительного (Брумзик с сестру ростом)
    (
        "PREP_C_and_Noun",
        r"(<exception regexp=\"yes\">\[!\.\?\]</exception>)",
        rf'\1<exception regexp="yes" scope="next">{SIZE}</exception>',
        1,
        ["Брумзик с сестру ростом.", "Камень с собаку величиной лежал у дороги."],
        [("Брумзик гулял с собаку по парку.", None)],
    ),
    # вин. п. неодушевлённого после «с» бывает сравнением без слова размера (Камень был с кулак): по форме не отличить
    # от ошибки («со стол»), такие случаи отдаём подсказке PREP_C_and_Noun_V
    (
        "PREP_C_and_Noun",
        r"(<exception regexp=\"yes\">\[!\.\?\]</exception>)",
        r'\1<exception postag="NN:Inanim:.*:V" postag_regexp="yes"/>',
        1,
        ["Камень был с кулак.", "Брумзик пришёл со стол."],
        [("Брумзик вернулся с работе.", None)],
    ),
    # пример ошибки правила «с рысь» теперь подсказка PREP_C_and_Noun_V («рысь» размечена и неодушевлённой): берём
    # однозначный им. п. одушевлённого (Егерь пошёл в лес с собака)
    (
        "PREP_C_and_Noun",
        r"<marker>с рысь</marker>",
        "<marker>с собака</marker>",
        1,
        ["Егерь пошёл в лес с рысью."],
        [("Егерь пошёл в лес с собака.", None)],
    ),
]

ADD = [
    # подсказка вместо ошибки: «с» + вин. п. неодушевлённого — опечатка («со стол») или сравнение («с кулак»)
    (
        "PREP_C_and_Noun",
        f"""
        <rule id="PREP_C_and_Noun_V" type="style" name="Предлог «с» и винительный падеж">
            <pattern case_sensitive="no">
                <token regexp="yes">с|со<exception regexp="yes" scope="previous">{SIZE}</exception></token>
                <token postag="NN:Inanim:.*:V" postag_regexp="yes"><exception regexp="yes">[!.?]</exception><exception regexp="yes" scope="next">{SIZE}</exception>{GEN2}{MEASURE}<exception postag="NN:.*:.*:(R|T)|UNKNOWN" postag_regexp="yes"/><exception postag="NN:.*:.*:.*|SENT_END|PARA_END" negate_pos="yes" postag_regexp="yes"/></token>
            </pattern>
            <message>Возможно, после «\\1» нужен родительный или творительный падеж; если это сравнение по величине («с кулак»), ошибки нет.</message>
            <short>Возможно, нужен родительный или творительный падеж</short>
            <example correction="">Брумзик пришёл <marker>со стол</marker>.</example>
            <example>Брумзик пришёл со стола.</example>
        </rule>""",
        [
            "Брумзик пришёл со стола.",
            "Доска толщиной с ладонь.",
            "Брумзик ждал с неделю.",
            "Брумзик сидел с краю.",
            "Брумзик гулял с собаку.",
        ],
        [("Камень был с кулак.", None), ("Брумзик пришёл со стол.", None), ("Брумзик пошёл в лес с рысь.", None)],
    ),
]
